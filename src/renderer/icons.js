function toolStatusHtml(status) {
  const icon = TOOL_STATUS_ICONS[status] || 'info';
  const text = TOOL_STATUS_LABELS[status] || status;
  return iconLabel(icon, text, status === 'running' ? 'icon-xs icon-spin' : 'icon-xs');
}

