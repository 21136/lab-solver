function svgMarkup(name, size = 24) {
  const inner = ICON_PATHS[name];
  if (!inner) return '';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
}

function iconHtml(name, opts = {}) {
  const cls = ['icon', opts.className].filter(Boolean).join(' ');
  const size = opts.size || 24;
  return `<span class="${cls}" role="img"${opts.label ? ` aria-label="${opts.label}"` : ''}>${svgMarkup(name, size)}</span>`;
}

function iconLabel(name, text, className = 'icon-xs') {
  return `${iconHtml(name, { className })}<span class="icon-text">${text}</span>`;
}

function setIconText(el, iconName, text, iconClass = 'icon-sm') {
  if (!el) return;
  el.innerHTML = iconLabel(iconName, text, iconClass);
}

function initDataIcons(root = document) {
  root.querySelectorAll('[data-icon]:not([data-icon-inited])').forEach((el) => {
    const name = el.getAttribute('data-icon');
    if (!ICON_PATHS[name]) return;
    el.setAttribute('data-icon-inited', '1');
    el.classList.add('icon');
    el.setAttribute('aria-hidden', 'true');
    el.innerHTML = svgMarkup(name, parseInt(el.getAttribute('data-icon-size') || '24', 10));
  });
}

